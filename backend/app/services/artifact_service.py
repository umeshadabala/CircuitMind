import io
import zipfile
import json
from typing import Dict, Any, List
from backend.app.models.project import Project, BuildGuide, GuideStep, FirmwareArtifact
from backend.app.catalog.boards import BOARDS
from backend.app.catalog.components import COMPONENTS_CATALOG
from backend.app.engine.generator import generate_wokwi_diagram, generate_firmware_code, generate_build_guide

class ArtifactGeneratorService:
    """
    ArtifactGeneratorService:
    Transforms the canonical Project Graph into verified engineering artifacts:
    - Wokwi diagram.json
    - wokwi.toml
    - sketch.ino firmware source
    - Step-by-step Assembly Guide (BUILD_GUIDE.md)
    - Full export ZIP bundle
    """

    @classmethod
    def generate_diagram(cls, project: Project) -> Dict[str, Any]:
        """Generates authentic Wokwi diagram.json matching project graph components & pins."""
        return generate_wokwi_diagram(project)

    @classmethod
    def generate_firmware(cls, project: Project) -> FirmwareArtifact:
        """Generates Arduino / C++ firmware source with macro definitions bound to pin assignments."""
        code = generate_firmware_code(project)
        return FirmwareArtifact(
            filename="sketch.ino",
            code=code,
            language="cpp",
            libraries=cls._extract_libraries(project),
            version=project.version
        )

    @classmethod
    def generate_wokwi_toml(cls, project: Project) -> str:
        """Generates wokwi.toml configuration for Wokwi CLI or Wokwi VS Code integration."""
        board_arch = project.board.architecture.lower()
        if "esp32" in project.board.type.lower():
            binary_name = "sketch.bin"
            elf_name = "sketch.elf"
        else:
            binary_name = "sketch.hex"
            elf_name = "sketch.elf"

        return f"""# Wokwi CLI Configuration File
# Generated by CircuitMind AI Engineering IDE
# Target Board: {project.board.display_name} ({project.board.type})

[wokwi]
version = 1
firmware = "{binary_name}"
elf = "{elf_name}"
"""

    @classmethod
    def generate_guide(cls, project: Project) -> BuildGuide:
        """Generates comprehensive physical assembly guide from project graph."""
        return generate_build_guide(project)

    @classmethod
    def generate_bundle(cls, project: Project, simulation_runs: List[Dict[str, Any]] = None) -> bytes:
        """Builds an in-memory zip archive with all project source, diagrams, tests, and documentation."""
        diagram = cls.generate_diagram(project)
        wokwi_toml = cls.generate_wokwi_toml(project)
        firmware_code = project.firmware[0].code if project.firmware else generate_firmware_code(project)

        zip_buffer = io.BytesIO()
        with zipfile.ZipFile(zip_buffer, "w", zipfile.ZIP_DEFLATED) as zf:
            zf.writestr("project.json", json.dumps(project.model_dump(), indent=2))
            zf.writestr("diagram.json", json.dumps(diagram, indent=2))
            zf.writestr("wokwi.toml", wokwi_toml)
            zf.writestr("firmware/sketch.ino", firmware_code)
            zf.writestr("tests/tests.json", json.dumps([t.model_dump() for t in project.tests], indent=2))

            # BOM
            bom = {
                "project_id": project.id,
                "title": project.title,
                "board": project.board.model_dump(),
                "components": [c.model_dump() for c in project.components],
                "pin_assignments": [pa.model_dump() for pa in project.pin_assignments]
            }
            zf.writestr("bom.json", json.dumps(bom, indent=2))
            
            # BOM CSV
            bom_csv = "instance_id,part_id,name,category\n"
            for c in project.components:
                bom_csv += f"{c.id},{c.part_id},\"{c.name}\",{c.category}\n"
            zf.writestr("bom.csv", bom_csv)

            # Build Guide Markdown
            guide_md = f"# {project.title} - Assembly Guide\n\n{project.build_guide.summary if project.build_guide else ''}\n\n## Hardware Inventory\n"
            for c in project.components:
                guide_md += f"- **{c.name}** (`{c.part_id}`)\n"

            guide_md += "\n## Assembly Steps\n"
            if project.build_guide:
                for s in project.build_guide.steps:
                    guide_md += f"### Step {s.step_number}: {s.title}\n{s.instructions}\n**Expected Result:** {s.expected_result}\n\n"

            if project.build_guide and project.build_guide.electrical_cautions:
                guide_md += "## Electrical & Safety Cautions\n"
                for caution in project.build_guide.electrical_cautions:
                    guide_md += f"- ⚠ {caution}\n"

            zf.writestr("documentation/BUILD_GUIDE.md", guide_md)
            zf.writestr("wiring_guide.md", guide_md)

            # README.md
            readme_md = f"""# {project.title}

AI-Native Engineering Project generated by CircuitMind IDE.
Tagline: Think it. Build it. Prove it.

## Overview
{project.description}

## Target Architecture
- **Microcontroller:** {project.board.display_name}
- **Architecture:** {project.board.architecture}
- **Logic Voltage:** {project.board.voltage_logic}V TTL

## Simulation
Run locally with the Wokwi CLI:
```bash
wokwi-cli .
```
Or open [Wokwi Simulator](https://wokwi.com) and import `diagram.json` and `firmware/sketch.ino`.
"""
            zf.writestr("README.md", readme_md)

            if simulation_runs:
                # Strictly isolate simulation runs: must match project_id and project.version
                valid_runs = [
                    r for r in simulation_runs 
                    if r.get("project_id") == project.id and r.get("version") == project.version
                ]
                if valid_runs:
                    zf.writestr("simulation/latest_run.json", json.dumps(valid_runs[0], indent=2))

        zip_buffer.seek(0)
        return zip_buffer.getvalue()

    @classmethod
    def generate_export_bundle(cls, project: Project) -> Dict[str, Any]:
        """Returns dictionary of all export files and their serialized string contents."""
        diagram = cls.generate_diagram(project)
        firmware_code = project.firmware[0].code if project.firmware else generate_firmware_code(project)
        guide = cls.generate_guide(project)
        bom = {
            "project_id": project.id,
            "title": project.title,
            "board": project.board.model_dump(),
            "components": [c.model_dump() for c in project.components],
            "pin_assignments": [pa.model_dump() for pa in project.pin_assignments]
        }
        return {
            "project.json": project.model_dump_json(indent=2),
            "sketch.ino": firmware_code,
            "diagram.json": json.dumps(diagram, indent=2),
            "bom.json": json.dumps(bom, indent=2),
            "README.md": f"# {project.title}\n\n{project.description}",
            "BUILD_GUIDE.md": guide.summary if guide else ""
        }

    @classmethod
    def _extract_libraries(cls, project: Project) -> List[str]:
        libs = []
        for comp in project.components:
            cat = COMPONENTS_CATALOG.get(comp.part_id, {})
            for lib in cat.get("firmware_libraries", []):
                if lib not in libs:
                    libs.append(lib)
        return libs
